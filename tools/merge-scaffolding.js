#!/usr/bin/env node
// Merges a linguist-corrected DRAFT file into the clean working scaffolding CSV.
//
// Input:  data/scaffolding/<pair>.DRAFT.csv, with verdict/corrected_text filled in.
// Output: data/scaffolding/<pair>.csv (the real working file), upserted by
//         utterance_id -- rows already in the working file that this merge
//         doesn't touch are left alone, so hand-authored entries survive.
//
// verdict handling:
//   keep    -> use text_draft as-is
//   fix     -> use corrected_text (must be non-empty)
//   reject  -> excluded from the working file entirely
//   (blank) -> not yet reviewed, excluded with a warning
//
// DRAFT columns don't carry every column the working schema has
// (switch_type, selection_rationale, reviewed_by) -- those are left for
// linguist follow-up and flagged in `notes`. See the mapping this script
// applies below.
//
// Also reports the rejection rate per category -- prints to console and
// writes data/scaffolding/<pair>.rejection-report.md.
//
// Usage: node merge-scaffolding.js <pair>   e.g. node merge-scaffolding.js sw-en

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { readCsvObjects, writeCsv } from "./csv-utils.js"

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, "..")
const SCAFFOLDING_DIR = path.join(ROOT, "data/scaffolding")

const WORKING_HEADER = [
  "utterance_id",
  "pedagogical_function",
  "tarl_level",
  "audience",
  "text",
  "switch_points",
  "switch_type",
  "register_note",
  "selection_rationale",
  "reviewed_by",
  "review_status",
  "notes",
]

const VALID_VERDICTS = new Set(["keep", "fix", "reject"])

function pickText(row) {
  if (row.verdict === "keep") return row.text_draft
  if (row.verdict === "fix") return row.corrected_text
  return null
}

function main() {
  const pair = process.argv[2]
  if (!pair) {
    console.error("Usage: node merge-scaffolding.js <pair>   e.g. sw-en")
    process.exit(1)
  }

  const draftPath = path.join(SCAFFOLDING_DIR, `${pair}.DRAFT.csv`)
  const workingPath = path.join(SCAFFOLDING_DIR, `${pair}.csv`)

  if (!fs.existsSync(draftPath)) {
    console.error(`No DRAFT file found at ${draftPath}. Run generate-scaffolding.js first.`)
    process.exit(1)
  }

  const { records: draftRows } = readCsvObjects(draftPath)

  const byCategory = {} // category -> { total, rejected, unresolved }
  const merged = [] // rows to upsert into the working file
  const warnings = []

  for (const row of draftRows) {
    const cat = byCategory[row.category] ?? { total: 0, rejected: 0, unresolved: 0 }
    cat.total++
    byCategory[row.category] = cat

    if (row.verdict === "") {
      cat.unresolved++
      warnings.push(`${row.act_id}: no verdict yet, skipped`)
      continue
    }

    if (!VALID_VERDICTS.has(row.verdict)) {
      warnings.push(`${row.act_id}: unrecognized verdict "${row.verdict}", skipped`)
      continue
    }

    if (row.verdict === "reject") {
      cat.rejected++
      continue
    }

    const text = pickText(row)
    if (!text) {
      warnings.push(`${row.act_id}: verdict is "fix" but corrected_text is empty, skipped`)
      continue
    }

    const notes = []
    if (row.verdict === "fix") {
      notes.push("switch_points not re-verified against corrected_text -- check before use.")
    }
    notes.push(`Generated from data/spec/dialogue-acts.csv act ${row.act_id}.`)
    notes.push("switch_type and selection_rationale still need linguist annotation.")

    merged.push({
      utterance_id: row.act_id,
      pedagogical_function: row.category,
      tarl_level: row.tarl_level || "any",
      audience: row.audience || "child",
      text,
      switch_points: row.switch_points,
      switch_type: "",
      register_note: row.register_note,
      selection_rationale: "",
      reviewed_by: "TBD -- pending named reviewer",
      review_status: "reviewed",
      notes: notes.join(" "),
    })
  }

  // Upsert into the existing working file by utterance_id, preserving rows
  // this merge doesn't touch (e.g. hand-authored entries).
  let existing = []
  if (fs.existsSync(workingPath)) {
    existing = readCsvObjects(workingPath).records
  }
  const byId = new Map(existing.map((r) => [r.utterance_id, r]))
  let added = 0
  let updated = 0
  for (const row of merged) {
    if (byId.has(row.utterance_id)) updated++
    else added++
    byId.set(row.utterance_id, row)
  }

  writeCsv(workingPath, WORKING_HEADER, Array.from(byId.values()))

  // Rejection-rate report.
  let report = `# Scaffolding rejection report -- ${pair}\n\n`
  report += `Generated by \`tools/merge-scaffolding.js\` from \`${pair}.DRAFT.csv\`.\n\n`
  report += "| Category | Total | Rejected | Unresolved | Rejection rate |\n"
  report += "|---|---|---|---|---|\n"
  let grandTotal = 0
  let grandRejected = 0
  for (const [cat, stats] of Object.entries(byCategory).sort()) {
    const rate = stats.total > 0 ? ((stats.rejected / stats.total) * 100).toFixed(1) : "0.0"
    report += `| ${cat} | ${stats.total} | ${stats.rejected} | ${stats.unresolved} | ${rate}% |\n`
    grandTotal += stats.total
    grandRejected += stats.rejected
  }
  const overallRate = grandTotal > 0 ? ((grandRejected / grandTotal) * 100).toFixed(1) : "0.0"
  report += `| **All categories** | **${grandTotal}** | **${grandRejected}** | | **${overallRate}%** |\n`

  const reportPath = path.join(SCAFFOLDING_DIR, `${pair}.rejection-report.md`)
  fs.writeFileSync(reportPath, report)

  console.log(`\n=== ${pair} merge summary ===`)
  console.log(`Rows added to working file: ${added}`)
  console.log(`Rows updated in working file: ${updated}`)
  console.log(`Rows excluded (reject/unresolved/error): ${draftRows.length - merged.length}`)
  if (warnings.length > 0) {
    console.log("Warnings:")
    for (const w of warnings) console.log(`  - ${w}`)
  }
  console.log(`\nRejection rate by category:\n`)
  console.log(report)
  console.log(`Working file: ${workingPath}`)
  console.log(`Rejection report: ${reportPath}`)
}

main()
